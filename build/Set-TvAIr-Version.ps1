[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string]$ProductVersion,

    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string]$PluginSdkVersion,

    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string]$PluginHostContractVersion
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$propsPath = Join-Path $root 'Directory.Build.props'

[xml]$props = Get-Content -LiteralPath $propsPath -Raw -Encoding UTF8
$group = $props.Project.PropertyGroup | Select-Object -First 1
if ($null -eq $group) { throw 'Directory.Build.props の PropertyGroup が見つかりません。' }

$oldProductVersion = [string]$group.TvAIrProductVersion
$group.TvAIrProductVersion = $ProductVersion
$group.TvAIrFileVersion = "$ProductVersion.0"
$group.TvAIrAssemblyVersion = "$ProductVersion.0"
if ($PSBoundParameters.ContainsKey('PluginSdkVersion')) {
    $group.TvAIrPluginSdkVersion = $PluginSdkVersion
}
if ($PSBoundParameters.ContainsKey('PluginHostContractVersion')) {
    $group.TvAIrPluginHostContractVersion = $PluginHostContractVersion
}

$settings = New-Object System.Xml.XmlWriterSettings
$settings.Indent = $true
$settings.IndentChars = '  '
$settings.NewLineChars = "`r`n"
$settings.NewLineHandling = 'Replace'
$settings.Encoding = New-Object System.Text.UTF8Encoding($false)
$writer = [System.Xml.XmlWriter]::Create($propsPath, $settings)
try { $props.Save($writer) } finally { $writer.Dispose() }

$product = [string]$group.TvAIrProductVersion
$sdk = [string]$group.TvAIrPluginSdkVersion
$hostContract = [string]$group.TvAIrPluginHostContractVersion
$minimumHost = [string]$group.TvAIrMinimumSupportedPluginHostContractVersion
$compatibilityMajor = [string]$group.TvAIrPluginCompatibilityMajor
$publicContractName = [string]$group.TvAIrPublicContractName
$hostContractContractName = [string]$group.TvAIrPluginHostContractName

$versionContract = @"
// <auto-generated />
#nullable enable
namespace TvAIr.Core;

/// <summary>Directory.Build.propsから生成されるTvAIr製品版・Plugin SDK・Plugin Host契約の正本。</summary>
internal static class TvAIrVersionContract
{
    public const string ProductName = "TvAIr";
    public const string ProductVersion = "$product";
    public const string PluginSdkVersion = "$sdk";
    public const string PluginHostContractVersion = "$hostContract";
    public const string MinimumSupportedPluginHostContractVersion = "$minimumHost";
    public const int PluginCompatibilityMajor = $compatibilityMajor;
    public const string PublicContractName = "$publicContractName";
    public const string PluginHostContractName = "$hostContractContractName";

    public static bool IsPreFoundationPluginContract(string? version)
    {
        if (string.IsNullOrWhiteSpace(version)) return false;
        return global::System.Version.TryParse(NormalizeVersion(version), out var parsed)
            && parsed.Major < PluginCompatibilityMajor;
    }

    public static bool IsSupportedPluginContract(string? version)
    {
        if (string.IsNullOrWhiteSpace(version)) return true;
        return global::System.Version.TryParse(NormalizeVersion(version), out var parsed)
            && parsed.Major == PluginCompatibilityMajor
            && parsed.CompareTo(new global::System.Version(MinimumSupportedPluginHostContractVersion)) >= 0;
    }

    public static bool IsFutureUnsupportedPluginContract(string? version)
    {
        if (string.IsNullOrWhiteSpace(version)) return false;
        return global::System.Version.TryParse(NormalizeVersion(version), out var parsed)
            && parsed.Major > PluginCompatibilityMajor;
    }

    public static string NormalizeVersion(string value)
    {
        var v = value.Trim();
        if (v.StartsWith("v", global::System.StringComparison.OrdinalIgnoreCase)) v = v[1..];
        var dash = v.IndexOf('-');
        if (dash >= 0) v = v[..dash];
        return v.Replace('_', '.');
    }
}
"@
Set-Content -LiteralPath (Join-Path $root 'TvAIr\Core\TvAIrVersionContract.generated.cs') -Value $versionContract -Encoding utf8

$sdkContract = @"
// <auto-generated />
#nullable enable
namespace TvAIrPlugin;

/// <summary>Directory.Build.propsから生成されるTvAIrPlugin SDK 1.0.0以降の公開契約正本。</summary>
public static class TvAIrPluginSdkContract
{
    public const string SdkVersion = "$sdk";
    public const string HostContractVersion = "$hostContract";
    public const string MinimumSupportedHostContractVersion = "$minimumHost";
    public const int CompatibilityMajor = $compatibilityMajor;

    public static bool IsCompatibleHostMajor(string? hostContractVersion)
    {
        if (string.IsNullOrWhiteSpace(hostContractVersion)) return true;
        return global::System.Version.TryParse(NormalizeVersion(hostContractVersion), out var parsed)
            && parsed.Major == CompatibilityMajor
            && parsed.CompareTo(new global::System.Version(MinimumSupportedHostContractVersion)) >= 0;
    }

    public static string NormalizeVersion(string value)
    {
        var v = value.Trim();
        if (v.StartsWith("v", global::System.StringComparison.OrdinalIgnoreCase)) v = v[1..];
        var dash = v.IndexOf('-');
        if (dash >= 0) v = v[..dash];
        return v.Replace('_', '.');
    }
}
"@
Set-Content -LiteralPath (Join-Path $root 'TvAIrPlugin\TvAIrPluginSdkContract.generated.cs') -Value $sdkContract -Encoding utf8

function Update-TextFile([string]$relativePath, [scriptblock]$transform) {
    $path = Join-Path $root $relativePath
    if (-not (Test-Path -LiteralPath $path)) { throw "更新対象が見つかりません: $relativePath" }
    $before = Get-Content -LiteralPath $path -Raw -Encoding UTF8
    $after = & $transform $before
    if ($after -ne $before) {
        Set-Content -LiteralPath $path -Value $after -Encoding utf8
    }
}

Update-TextFile 'README.md' {
    param($text)
    $text = [regex]::Replace($text, '(?m)^# TvAIr \d+\.\d+\.\d+$', "# TvAIr $product", 1)
    [regex]::Replace($text, 'TvAIr \d+\.\d+\.\d+のVisual Studio 2022用ソース一式です。', "TvAIr $productのVisual Studio 2022用ソース一式です。", 1)
}
Update-TextFile 'README.txt' {
    param($text)
    [regex]::Replace($text, '(?m)^TvAIr \d+\.\d+\.\d+ README$', "TvAIr $product README", 1)
}
Update-TextFile 'RELEASE_NOTES.txt' {
    param($text)
    [regex]::Replace($text, '(?m)^TvAIr \d+\.\d+\.\d+$', "TvAIr $product", 1)
}

$webFiles = Get-ChildItem -LiteralPath (Join-Path $root 'TvAIr\wwwroot') -Recurse -File |
    Where-Object { $_.Extension -in '.html', '.js', '.css' }
$programPath = Join-Path $root 'TvAIr\Program.cs'
$projectionFiles = @($webFiles.FullName) + $programPath
foreach ($path in $projectionFiles) {
    $text = Get-Content -LiteralPath $path -Raw -Encoding UTF8
    $updated = $text
    if (-not [string]::IsNullOrWhiteSpace($oldProductVersion)) {
        $escapedOld = [regex]::Escape($oldProductVersion)
        $updated = [regex]::Replace($updated, "(?<=\?v=)$escapedOld", $product)
        $updated = $updated.Replace("TVA_IR_UI_VERSION=\"$oldProductVersion\"", "TVA_IR_UI_VERSION=\"$product\"")
        $updated = $updated.Replace("version:'$oldProductVersion'", "version:'$product'")
    }
    if ($updated -ne $text) {
        Set-Content -LiteralPath $path -Value $updated -Encoding utf8
    }
}

& (Join-Path $PSScriptRoot 'Verify-TvAIr-Version.ps1')
Write-Host "TvAIr product version updated: $oldProductVersion -> $product"
Write-Host "Plugin SDK contract remains: $sdk"
Write-Host "Plugin Host contract remains: $hostContract"
